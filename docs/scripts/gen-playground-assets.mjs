// Prepares the two static assets the in-browser playground fetches at runtime,
// both derived from helix's BUILT dist (so `npm --prefix ../helix run build`
// must have run first):
//
//   public/versions/<id>.json  - the raw mcmeta version data. The playground
//       feeds these to `profileFromRaw` to build a VersionProfile in the browser
//       (helix's Node build reads them from disk at import time; the browser
//       can't, so we serve them and fetch on demand).
//
//   public/helix-types.json    - a { "<rel path>": "<.d.ts contents>" } map of
//       every declaration file in helix's dist. The playground loads each as a
//       Monaco `extraLib` so authoring code gets real autocomplete/hover on the
//       helix API. Bundled into one JSON so it's a single request.
//
// Both live under public/ (git-ignored) and are regenerated by `gen:playground`,
// which runs before `dev`/`build`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = join(here, "..");
const helixDist = join(docsRoot, "..", "helix", "dist");
const publicDir = join(docsRoot, "public");

function walk(dir, test) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, test));
    else if (entry.isFile() && test(entry.name)) out.push(full);
  }
  return out;
}

function ensureDistBuilt() {
  try {
    statSync(join(helixDist, "browser.d.ts"));
  } catch {
    throw new Error(
      "helix dist not found (expected helix/dist/browser.d.ts).\n" +
        "Build helix first: `npm --prefix ../helix run build`.",
    );
  }
}

ensureDistBuilt();

// 1. Version data JSON -> public/versions/
const dataDir = join(helixDist, "versions", "data");
const versionsOut = join(publicDir, "versions");
mkdirSync(versionsOut, { recursive: true });
let versionCount = 0;
for (const file of walk(dataDir, (n) => n.endsWith(".json"))) {
  writeFileSync(join(versionsOut, relative(dataDir, file)), readFileSync(file));
  versionCount++;
}

// 2. All .d.ts -> public/helix-types.json (keyed by dist-relative path)
const types = {};
for (const file of walk(helixDist, (n) => n.endsWith(".d.ts"))) {
  types[relative(helixDist, file).split("\\").join("/")] = readFileSync(file, "utf8");
}
mkdirSync(publicDir, { recursive: true });
writeFileSync(join(publicDir, "helix-types.json"), JSON.stringify(types));

console.log(
  `playground assets: ${versionCount} version file(s) -> public/versions/, ` +
    `${Object.keys(types).length} .d.ts -> public/helix-types.json`,
);
